it('keeps display stars inert and exposes translated, disabled icon actions', async () => {
  const save=vi.fn()
  const rating={id:'a',value:3,date:'2024-01-01',createdAt:1,revision:1}
  const {rerender}=render(<BookRatingsView model={model({ratings:[rating],save})} />)
  fireEvent.click(screen.getByRole('img',{name:'3 étoiles'}))
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  const edit=screen.getByRole('button',{name:'Modifier l’évaluation'})
  act(()=>edit.focus())
  expect(screen.getByRole('tooltip')).toHaveTextContent('Modifier l’évaluation')
  expect(screen.getByRole('button',{name:'Supprimer l’évaluation'})).toBeEnabled()
  await act(async()=>i18n.changeLanguage('en'))
  expect(screen.getByRole('button',{name:'Edit rating'})).toBeInTheDocument()
  expect(screen.getByRole('button',{name:'Delete rating'})).toBeInTheDocument()
  rerender(<BookRatingsView model={model({ratings:[rating],busy:true,save})} />)
  expect(screen.getByRole('button',{name:'Edit rating'})).toBeDisabled()
  expect(save).not.toHaveBeenCalled()
})
it('creates an optional plain-text impression, preserves it during star/date edits, and allows clearing it',async()=>{
  render(<BookNotesPreview />)
  fireEvent.click(screen.getByRole('button',{name:'Ajouter une évaluation'}))
  let dialog=screen.getByRole('dialog')
  const input=within(dialog).getByRole('textbox',{name:'Petite phrase (facultative)'})
  expect(input).toHaveAttribute('maxlength','160')
  fireEvent.change(input,{target:{value:'Une impression <b>en texte simple</b>.'}})
  expect(input).toHaveAccessibleDescription('38/160')
  fireEvent.click(within(dialog).getByRole('button',{name:'5 étoiles'}))
  fireEvent.click(within(dialog).getByRole('button',{name:'Enregistrer'}))
  await waitFor(()=>expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
  let row=articles()[0]
  expect(row).toHaveTextContent('Une impression <b>en texte simple</b>.')
  expect(row.querySelector('b')).toBeNull()
  fireEvent.click(within(row).getByRole('button',{name:'Modifier l’évaluation'}))
  dialog=screen.getByRole('dialog')
  expect(within(dialog).getByRole('textbox',{name:'Petite phrase (facultative)'})).toHaveValue('Une impression <b>en texte simple</b>.')
  fireEvent.click(within(dialog).getByRole('button',{name:'2 étoiles'}))
  fireEvent.click(within(dialog).getByLabelText('Date de l’évaluation'))
  const calendar=screen.getByRole('dialog',{name:'Date de l’évaluation'})
  fireEvent.keyDown(document.activeElement,{key:'ArrowRight'})
  fireEvent.keyDown(document.activeElement,{key:'Enter'})
  expect(calendar).not.toBeInTheDocument()
  fireEvent.click(within(dialog).getByRole('button',{name:'Enregistrer'}))
  await waitFor(()=>expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
  row=articles()[0]
  expect(row).toHaveTextContent('Une impression <b>en texte simple</b>.')
  expect(within(row).getByRole('img',{name:'2 étoiles'})).toBeInTheDocument()
  fireEvent.click(within(row).getByRole('button',{name:'Modifier l’évaluation'}))
  dialog=screen.getByRole('dialog')
  fireEvent.change(within(dialog).getByRole('textbox',{name:'Petite phrase (facultative)'}),{target:{value:''}})
  fireEvent.click(within(dialog).getByRole('button',{name:'Enregistrer'}))
  await waitFor(()=>expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
  expect(articles()[0].querySelector('p')).toBeNull()
  fireEvent.click(within(articles()[0]).getByRole('button',{name:'Supprimer l’évaluation'}))
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button',{name:'Supprimer'}))
  await waitFor(()=>expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
  expect(screen.queryByText('Une impression <b>en texte simple</b>.')).not.toBeInTheDocument()
})
