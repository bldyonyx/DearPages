it('shows empty/loading/error states and disables writes while pending', () => {
  const {rerender}=render(<BookRatingsView model={model()} />)
  expect(screen.getByText('Pas encore d’évaluation.')).toBeInTheDocument()
  rerender(<BookRatingsView model={model({loading:true})} />)
  expect(screen.getByRole('button',{name:'Ajouter une évaluation'})).toBeDisabled()
  expect(screen.getByRole('status')).toHaveTextContent('Chargement')
  rerender(<BookRatingsView model={model({busy:true,error:'conflict'})} />)
  expect(screen.getByRole('alert')).toHaveTextContent('a changé')
  expect(screen.getByRole('button',{name:'Ajouter une évaluation'})).toBeDisabled()
})
it('keeps an unsuccessful draft and displays an error, with no silent dismissal', async () => {
  const save=vi.fn(async()=>false)
  const {rerender}=render(<BookRatingsView model={model({create:save})} />)
  fireEvent.click(screen.getByRole('button',{name:'Ajouter une évaluation'}))
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button',{name:'2 étoiles'}))
  await act(async()=>fireEvent.click(within(screen.getByRole('dialog')).getByRole('button',{name:'Enregistrer'})))
  rerender(<BookRatingsView model={model({create:save,error:'saveError'})} />)
  expect(screen.getByRole('dialog')).toHaveTextContent('Ton brouillon est conservé')
  expect(within(screen.getByRole('dialog')).getByRole('button',{name:'2 étoiles'})).toHaveAttribute('aria-pressed','true')
  expect(save.mock.calls[0][0]).toBe('stable')
})
it('supports keyboard navigation in the shared calendar and restores focus on Escape', async () => {
  render(<BookNotesPreview />)
  fireEvent.click(screen.getByRole('button',{name:'Ajouter une évaluation'}))
  const trigger=within(screen.getByRole('dialog')).getByLabelText('Date de l’évaluation')
  fireEvent.click(trigger)
  const calendar=screen.getByRole('dialog',{name:'Date de l’évaluation'})
  const focused=document.activeElement
  expect(calendar).toContainElement(focused)
  expect(focused).toHaveAttribute('data-date')
  fireEvent.keyDown(focused,{key:'ArrowRight'})
  expect(document.activeElement).not.toBe(focused)
  fireEvent.keyDown(document.activeElement,{key:'Enter'})
  expect(screen.queryByRole('dialog',{name:'Date de l’évaluation'})).not.toBeInTheDocument()
  expect(trigger).toHaveFocus()
  fireEvent.click(trigger)
  fireEvent.keyDown(screen.getByRole('dialog',{name:'Date de l’évaluation'}),{key:'Escape'})
  expect(trigger).toHaveFocus()
})
