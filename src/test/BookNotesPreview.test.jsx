import { fireEvent, render, screen, within } from '@testing-library/react'
import { expect, it, vi } from 'vitest'
import BookNotesPreview from '../preview/BookNotesPreview.jsx'
import i18n from '../i18n/index.js'
vi.mock('../services/firebase.js', () => { throw new Error('Preview must not import Firebase') })
it('pins and unpins several preview notes without Firebase, including an untitled collapsed note', async () => {
  await i18n.changeLanguage('fr')
  render(<BookNotesPreview />)
  const untitled = screen.getByRole('article', { name: 'Note sans titre' })
  fireEvent.click(within(untitled).getByRole('button', { name: 'Épingler la note' }))
  expect(screen.getAllByRole('article').filter(article => article.getAttribute('aria-label') !== 'Évaluation')[0]).toBe(untitled)
  expect(untitled.querySelector('[aria-expanded]')).toHaveAttribute('aria-expanded', 'false')
  fireEvent.click(screen.getByRole('button', { name: 'Épingler la note' }))
  expect(screen.getAllByRole('button', { name: 'Désépingler la note' })).toHaveLength(2)
  fireEvent.click(within(untitled).getByRole('button', { name: 'Désépingler la note' }))
  expect(screen.getAllByRole('article').filter(article => article.getAttribute('aria-label') !== 'Évaluation')[1]).toBe(untitled)
})
it('uses the real status/date controls and keeps final dates outside personal space', async () => {
  await i18n.changeLanguage('fr')
  render(<BookNotesPreview />)
  const book=screen.getByRole('heading',{name:'Le Petit Prince'}).closest('header')
  const space=screen.getByRole('region',{name:'Mon espace de lecture'})
  expect(within(book).getByText('Lecture terminée')).toBeInTheDocument()
  expect(within(book).getByText('Juin 2024')).toBeInTheDocument()
  expect(within(space).queryByText('Juin 2024')).not.toBeInTheDocument()
  expect(screen.queryByLabelText('Disposition de la date')).not.toBeInTheDocument()
  fireEvent.click(within(book).getByRole('button',{name:'Modifier la date · Lecture terminée'}))
  fireEvent.click(within(book).getByRole('button',{name:'Juin'}))
  fireEvent.click(screen.getByRole('button',{name:'Juillet'}))
  fireEvent.click(within(book).getByRole('button',{name:'Enregistrer'}))
  await screen.findByText('Juillet 2024')
  fireEvent.click(within(book).getByRole('button',{name:'Terminé'}))
  fireEvent.click(screen.getByRole('button',{name:'Abandonné'}))
  expect(within(book).getByText('Lecture abandonnée')).toBeInTheDocument()
  expect(within(book).getByText('Mars 2026')).toBeInTheDocument()
  fireEvent.click(within(book).getByRole('button',{name:'Modifier la date · Lecture abandonnée'}))
  fireEvent.click(within(book).getByRole('button',{name:'Mars'}))
  fireEvent.click(screen.getByRole('button',{name:'Avril'}))
  fireEvent.click(within(book).getByRole('button',{name:'Enregistrer'}))
  await screen.findByText('Avril 2026')
  fireEvent.click(within(book).getByRole('button',{name:'Abandonné'}))
  fireEvent.click(screen.getByRole('button',{name:'Terminé'}))
  expect(within(book).getByText('Juillet 2024')).toBeInTheDocument()
  expect(within(space).queryByText('Lecture terminée')).not.toBeInTheDocument()
})
it('uses the same counter-only real rating form and preserves its draft on language changes', async () => {
  await i18n.changeLanguage('fr')
  render(<BookNotesPreview />)
  fireEvent.click(screen.getByRole('button',{name:'Ajouter une évaluation'}))
  const dialog=screen.getByRole('dialog')
  const input=within(dialog).getByRole('textbox',{name:'Petite phrase (facultative)'})
  expect(input).toHaveAttribute('maxlength','160')
  expect(input).toHaveAccessibleDescription('0/160')
  fireEvent.change(input,{target:{value:'x'.repeat(40)}})
  expect(input).toHaveAccessibleDescription('40/160')
  expect(within(dialog).queryByText(/Une impression rapide/)).not.toBeInTheDocument()
  expect(i18n.t('bookPage.ratings.impressionHint',{count:40})).toBe('40/160')
  fireEvent.change(screen.getByLabelText('Langue'),{target:{value:'en'}})
  const english=await screen.findByRole('textbox',{name:'Short impression (optional)'})
  expect(english).toHaveValue('x'.repeat(40))
  expect(english).toHaveAccessibleDescription('40/160')
})
